def to_simplified_chinese(text: str) -> str:
    try:
        from opencc import OpenCC

        return OpenCC("t2s").convert(text)
    except Exception:
        return text.translate(_TRADITIONAL_TO_SIMPLIFIED)


def clean_transcript_text(text: str) -> str:
    value = re.sub(r"\s+", " ", text or "").strip()
    value = value.strip(" \n\t`'\"“”‘’「」『』")
    if is_no_speech_placeholder(value):
        return ""
    return to_simplified_chinese(value)


def is_no_speech_placeholder(text: str) -> bool:
    value = re.sub(r"\s+", "", to_simplified_chinese(text or "").strip().lower())
    value = value.strip("。.!！?？,，;；:：'\"“”‘’「」『』()（）[]【】")
    if not value:
        return False
    placeholders = {
        "我没有收到任何音频",
        "我没有收到任何音频这句话",
        "没有收到任何音频",
        "我没有听到任何音频",
        "没有听到任何音频",
        "我没有听到任何说话内容",
        "没有听到任何说话内容",
        "音频中没有说话内容",
        "这段音频没有说话内容",
        "这段音频中没有说话内容",
        "音频中没有可转写内容",
        "这段音频没有可转写内容",
        "这段音频中没有可转写内容",
        "没有可转写的人声",
        "音频为空",
        "静音",
        "nospeech",
        "noaudio",
    }
    if value in placeholders:
        return True
    return bool(
        re.fullmatch(r"(我)?(没有|未)(收到|听到)(任何)?(音频|声音|说话内容|人声)", value)
        or re.fullmatch(r"(这段)?音频(中)?(没有|无)(可转写的?)?(说话内容|人声|语音内容|文本内容)", value)
    )


def _run_mlx_vlm_generate(
    *,
    audio_path: Path,
    model_path_or_repo: str,
    prompt: str,
    python_executable: str,
    is_canceled: Callable[[], bool],
) -> str:
    command = [
        python_executable,
        "-m",
        "mlx_vlm.generate",
        "--model",
        model_path_or_repo,
        "--audio",
        str(audio_path),
        "--prompt",
        prompt,
        "--max-tokens",
        str(settings.mlx_vlm_max_tokens),
    ]
    try:
        process = subprocess.Popen(
            command,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            encoding="utf-8",
            errors="ignore",
        )
    except OSError as exc:
        raise RuntimeError(f"无法启动 Gemma4 MLX VLM Audio：{exc}") from exc

    started_at = time.monotonic()
    try:
        while process.poll() is None:
            if time.monotonic() - started_at > settings.mlx_vlm_timeout_seconds:
                process.kill()
                raise RuntimeError(f"Gemma4 MLX VLM Audio 转录超时：超过 {settings.mlx_vlm_timeout_seconds} 秒")
            if is_canceled():
                process.terminate()
                try:
                    process.wait(timeout=5)
                except subprocess.TimeoutExpired:
                    process.kill()
                raise OperationCanceled("任务已停止")
            try:
                stdout, stderr = process.communicate(timeout=0.5)
            except subprocess.TimeoutExpired:
                continue
            break
        else:
            stdout, stderr = process.communicate()
    except subprocess.TimeoutExpired as exc:
        process.kill()
        raise RuntimeError(f"Gemma4 MLX VLM Audio 转录超时：{exc}") from exc

    if process.returncode != 0:
        detail = (stderr or stdout or "").strip()
        raise RuntimeError(f"Gemma4 MLX VLM Audio 转录失败：{detail}")
    transcript = clean_transcript_text(parse_mlx_vlm_generate_output(stdout))
    return transcript


