    del language
    status = mlx_vlm_audio_status(model_path_or_repo)
    if not status.available:
        raise RuntimeError(status.reason or "Gemma4 MLX VLM Audio 前置条件未满足。")

    active_work_dir = work_dir or audio_path.parent / "mlx_vlm_audio_work"
    base_metadata = {
        "engine": "mlx-vlm-audio",
        "backend": "mlx-vlm",
        "model": model_path_or_repo,
        "python": status.python_executable,
        "prompt": settings.mlx_vlm_prompt,
        "maxTokens": settings.mlx_vlm_max_tokens,
        "chunkSeconds": settings.mlx_vlm_chunk_seconds,
        "overlapSeconds": settings.mlx_vlm_overlap_seconds,
        "overlapDedupeStrategy": "common-prefix-suffix-boundary",
    }

    def transcribe_chunk(chunk_path: Path) -> str:
        return clean_transcript_text(
            _run_mlx_vlm_generate(
                audio_path=chunk_path,
                model_path_or_repo=model_path_or_repo,
                prompt=settings.mlx_vlm_prompt,
                python_executable=status.python_executable,
                is_canceled=is_canceled,
            )
        )

    model_label = f"{Path(model_path_or_repo).name or model_path_or_repo}（MLX VLM Audio）"
    segments, partial = transcribe_audio_in_chunks(
        audio_path=audio_path,
        work_dir=active_work_dir,
        config=ChunkTranscriptionConfig(
            namespace="mlx_vlm_audio",
            engine_name="mlx-vlm-audio",
            model_label=model_label,
            chunk_seconds=float(settings.mlx_vlm_chunk_seconds),
            overlap_seconds=float(settings.mlx_vlm_overlap_seconds),
            metadata=base_metadata,
        ),
        transcribe_chunk=transcribe_chunk,
        is_canceled=is_canceled,
        on_partial=on_partial,
    )
    duration = audio_duration_seconds(audio_path)
    metadata = {
        **base_metadata,
        "partial_results": partial,
        "finalJson": {
            "segments": partial,
            "full_text": segment_text(segments, include_timestamps=False),
        },
        "duration": round(duration, 3),
    }
    return AudioEngineResult.from_segments(
        segments=segments,
        engine_name="mlx-vlm-audio",
        model_label=model_label,
        metadata=metadata,
    )
